export interface GeneratedAgentArtifact {
  filename: string;
  format: AgentArtifactFormat;
  type: "markdown" | "text" | "json" | "file";
  mimeType: string;
  bytes: Buffer;
  contentText: string | null;
}

const MAX_ARTIFACT_BYTES = 20 * 1024 * 1024;

function artifactStem(taskTitle: string, definitionName: string) {
  return safeFileName(`${taskTitle}-${definitionName}`.normalize("NFKC").replace(/\s+/g, "-")).replace(/\.[^.]+$/, "").slice(0, 180) || "agent-output";
}

async function makeDocx(title: string, markdown: string) {
  // A4 with 2 cm margins: 9638 DXA of text width.
  const WIDTH = 9638;
  const children: (Paragraph | Table)[] = [
    new Paragraph({ text: title, heading: HeadingLevel.TITLE, alignment: AlignmentType.LEFT }),
    new Paragraph({ children: [new TextRun({ text: "Generated by Woli Agent Work", color: "667085", italics: true })], spacing: { after: 240 } }),
  ];
  for (const block of markdownBlocks(markdown)) {
    if (block.kind === "heading") {
      const heading = block.level === 1 ? HeadingLevel.HEADING_1 : block.level === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3;
      children.push(new Paragraph({ text: block.text, heading, spacing: { before: 180, after: 90 } }));
    } else if (block.kind === "bullet") children.push(new Paragraph({ text: block.text, bullet: { level: 0 }, spacing: { after: 70 } }));
    else if (block.kind === "paragraph") children.push(new Paragraph({ text: block.text, spacing: { after: 90, line: 300 } }));
    else if (block.kind === "table") {
      const widths = columnWidths(block, WIDTH).map(Math.floor);
      const size = block.header.length > 6 ? 16 : 18; // half-points
      const row = (cells: string[], head: boolean) =>
        new TableRow({
          tableHeader: head,
          children: cells.map(
            (text, i) =>
              new TableCell({
                width: { size: widths[i], type: WidthType.DXA },
                shading: head ? { type: ShadingType.CLEAR, fill: "EEF2FF", color: "auto" } : undefined,
                margins: { top: 50, bottom: 50, left: 80, right: 80 },
                children: [new Paragraph({ children: [new TextRun({ text, bold: head, size })] })],
              }),
          ),
        });
      children.push(new Table({ width: { size: WIDTH, type: WidthType.DXA }, columnWidths: widths, rows: [row(block.header, true), ...block.rows.map((r) => row(r, false))] }));
      children.push(new Paragraph({ text: "", spacing: { after: 120 } }));
    }
  }
  const doc = new Document({ sections: [{ properties: { page: { margin: { top: 1134, bottom: 1134, left: 1134, right: 1134 } } }, children }] });
  return Buffer.from(await Packer.toBuffer(doc));
}

/** Share of the width each column gets: by its longest cell, within limits so no column vanishes. */
function columnWidths(table: { header: string[]; rows: string[][] }, total: number): number[] {
  const weight = table.header.map((h, i) => {
    const longest = Math.max(h.length, ...table.rows.map((r) => (r[i] ?? "").length));
    return Math.min(42, Math.max(6, longest)) + 2;
  });
  const sum = weight.reduce((a, b) => a + b, 0);
  return weight.map((w) => (w / sum) * total);
}

type Cell = string | number | { t: "n"; v: number; z: string };
const xlsxCell = (text: string): Cell => {
  const v = cellValue(text);
  return typeof v === "object" ? { t: "n", v: v.percent, z: "0.00%" } : v;
};

/**
 * "Report": the whole result top to bottom, tables as real columns. One more sheet per table (named after
 * the heading above it) with a filter row, so the numbers can be sorted, filtered and summed.
 */
function makeXlsx(title: string, markdown: string) {
  const workbook = XLSX.utils.book_new();
  const blocks = markdownBlocks(markdown);
  const report: Cell[][] = [[title], [`Woli Agent Work - ${new Date().toISOString().slice(0, 10)}`], []];
  const tables: { name: string; table: Extract<MdBlock, { kind: "table" }> }[] = [];
  let lastHeading = "";
  let widest = 1;
  for (const block of blocks) {
    if (block.kind === "space") report.push([]);
    else if (block.kind === "heading") {
      lastHeading = block.text;
      report.push([block.text]);
    } else if (block.kind === "bullet") report.push([`• ${block.text}`]);
    else if (block.kind === "paragraph") report.push([block.text]);
    else {
      widest = Math.max(widest, block.header.length);
      report.push(block.header, ...block.rows.map((r) => r.map(xlsxCell)), []);
      tables.push({ name: lastHeading || `Table ${tables.length + 1}`, table: block });
    }
  }
  const sheet = XLSX.utils.aoa_to_sheet(report);
  sheet["!cols"] = Array.from({ length: widest }, (_, i) => ({ wch: i === 0 ? 44 : 20 }));
  XLSX.utils.book_append_sheet(workbook, sheet, "Report");
  const used = new Set(["report"]);
  for (const [n, { name, table }] of tables.entries()) {
    // Sheet names: at most 31 characters, none of : \\ / ? * [ ], unique.
    let base = name.replace(/[:\\/?*[\]]/g, " ").replace(/\s+/g, " ").trim().slice(0, 27) || `Table ${n + 1}`;
    if (used.has(base.toLowerCase())) base = `${base.slice(0, 24)} ${n + 1}`;
    used.add(base.toLowerCase());
    const ws = XLSX.utils.aoa_to_sheet([table.header, ...table.rows.map((r) => r.map(xlsxCell))]);
    ws["!cols"] = table.header.map((h, i) => ({ wch: Math.min(60, Math.max(10, h.length, ...table.rows.map((r) => (r[i] ?? "").length)) + 2) }));
    ws["!autofilter"] = { ref: XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: table.rows.length, c: table.header.length - 1 } }) };
    XLSX.utils.book_append_sheet(workbook, ws, base);
  }
  return Buffer.from(XLSX.write(workbook, { type: "buffer", bookType: "xlsx", compression: true }));
}

/** Blocks as plain lines (slides, text files): a table row becomes "a | b | c". */
function blockLines(markdown: string): string[] {
  return markdownBlocks(markdown).flatMap((block) =>
    block.kind === "space" ? [""] : block.kind === "table" ? [block.header.join(" | "), ...block.rows.map((r) => r.join(" | "))] : block.kind === "bullet" ? [`• ${block.text}`] : [block.text],
  );
}

function chunkText(text: string, max = 900) {
  const chunks: string[] = [];
  let remaining = text.trim();
  while (remaining) {
    if (remaining.length <= max) {
      chunks.push(remaining);
      break;
    }
    const cut = Math.max(200, remaining.lastIndexOf("\n", max), remaining.lastIndexOf(" ", max));
    chunks.push(remaining.slice(0, cut).trim());
    remaining = remaining.slice(cut).trim();
  }
  return chunks;
}

async function makePptx(title: string, markdown: string) {
  const presentation = new PptxGenJS();
  presentation.layout = "LAYOUT_WIDE";
  presentation.author = "Woli Agent Work";
  presentation.subject = "Agent-generated artifact";
  presentation.title = title;
  presentation.company = "Woli";
  presentation.theme = { headFontFace: "Aptos Display", bodyFontFace: "Aptos" };

  const cover = presentation.addSlide();
  cover.background = { color: "F7F8FA" };
  cover.addShape(presentation.ShapeType.rect, { x: 0, y: 0, w: 0.2, h: 7.5, fill: { color: "4F46E5" }, line: { color: "4F46E5" } });
  cover.addText(title, { x: 0.8, y: 2.35, w: 11.7, h: 1.2, fontFace: "Aptos Display", fontSize: 30, bold: true, color: "111827", margin: 0 });
  cover.addText("Generated by Woli Agent Work", { x: 0.82, y: 3.75, w: 7, h: 0.4, fontSize: 14, color: "667085", margin: 0 });

  const chunks = chunkText(blockLines(markdown).filter(Boolean).join("\n\n"));
  for (const [index, chunk] of chunks.entries()) {
    const slide = presentation.addSlide();
    slide.background = { color: "FFFFFF" };
    slide.addText(index === 0 ? title : `${title} (${index + 1})`, { x: 0.65, y: 0.45, w: 12, h: 0.55, fontSize: 22, bold: true, color: "1F2937", margin: 0 });
    slide.addShape(presentation.ShapeType.line, { x: 0.65, y: 1.15, w: 12, h: 0, line: { color: "E5E7EB", width: 1 } });
    slide.addText(chunk, { x: 0.75, y: 1.45, w: 11.8, h: 5.35, fontSize: 16, color: "374151", breakLine: false, valign: "top", margin: 0.08, paraSpaceAfter: 9, fit: "shrink" });
    slide.addText(`${index + 1} / ${chunks.length}`, { x: 11.5, y: 7.05, w: 1.1, h: 0.2, fontSize: 9, color: "9CA3AF", align: "right", margin: 0 });
  }
  const result = await presentation.write({ outputType: "nodebuffer", compression: true });
  return Buffer.from(result as Uint8Array);
}

// Noto Sans ships in per-script files: "vietnamese" holds only the extra Vietnamese letters, not a-z.
// A line is drawn piece by piece, each piece with the first file that has its characters.
const FONT_SUBSETS = ["latin", "vietnamese", "latin-ext"] as const;
const fontFile = (subset: string, weight: 400 | 700) => join(process.cwd(), "node_modules", "@fontsource", "noto-sans", "files", `noto-sans-${subset}-${weight}-normal.woff`);

interface Face {
  fonts: { font: PDFFont; has: Set<number> }[];
}
async function loadFace(pdf: PDFDocument, weight: 400 | 700): Promise<Face> {
  const fonts = [];
  for (const subset of FONT_SUBSETS) {
    const font = await pdf.embedFont(await readFile(fontFile(subset, weight)), { subset: true });
    fonts.push({ font, has: new Set(font.getCharacterSet()) });
  }
  return { fonts };
}

/** The text as runs of one font each; a character no file has becomes "?". */
function runs(face: Face, text: string): { font: PDFFont; text: string }[] {
  const out: { font: PDFFont; text: string }[] = [];
  for (const ch of text.normalize("NFC")) {
    const cp = ch.codePointAt(0)!;
    const hit = face.fonts.find((f) => f.has.has(cp));
    const font = (hit ?? face.fonts[0]).font;
    const piece = hit ? ch : cp < 32 ? "" : "?";
    const last = out[out.length - 1];
    if (last && last.font === font) last.text += piece;
    else out.push({ font, text: piece });
  }
  return out;
}
const textWidth = (face: Face, text: string, size: number) => runs(face, text).reduce((w, r) => w + r.font.widthOfTextAtSize(r.text, size), 0);

/** Wraps on spaces; a single word wider than the line (a link, an id) is broken across lines. */
function wrapPdfLine(text: string, face: Face, size: number, maxWidth: number): string[] {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(/\s+/).filter(Boolean)) {
    const candidate = line ? `${line} ${word}` : word;
    if (textWidth(face, candidate, size) <= maxWidth) {
      line = candidate;
      continue;
    }
    if (line) lines.push(line);
    line = word;
    while (textWidth(face, line, size) > maxWidth && line.length > 1) {
      let cut = line.length - 1;
      while (cut > 1 && textWidth(face, line.slice(0, cut), size) > maxWidth) cut--;
      lines.push(line.slice(0, cut));
      line = line.slice(cut);
    }
  }
  if (line) lines.push(line);
  return lines.length ? lines : [""];
}

async function makePdf(title: string, markdown: string) {
  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  const regular = await loadFace(pdf, 400);
  const bold = await loadFace(pdf, 700);
  const pageSize: [number, number] = [595.28, 841.89];
  const margin = 48;
  const width = pageSize[0] - margin * 2;
  let page = pdf.addPage(pageSize);
  let y = pageSize[1] - margin;
  const addPage = () => { page = pdf.addPage(pageSize); y = pageSize[1] - margin; };
  const draw = (text: string, x: number, at: number, size: number, face: Face, color: RGB) => {
    let cx = x;
    for (const r of runs(face, text)) {
      if (r.text) page.drawText(r.text, { x: cx, y: at, size, font: r.font, color });
      cx += r.font.widthOfTextAtSize(r.text, size);
    }
  };
  const drawLine = (line: string, size: number, face: Face, color: RGB, gap = 1.4, indent = 0) => {
    if (y < margin + size * gap) addPage();
    y -= size;
    draw(line, margin + indent, y, size, face, color);
    y -= size * (gap - 1);
  };
  const ink = rgb(0.17, 0.2, 0.27);
  const dark = rgb(0.08, 0.11, 0.18);
  const rule = rgb(0.82, 0.84, 0.88);

  for (const line of wrapPdfLine(title, bold, 18, width)) drawLine(line, 18, bold, dark, 1.3);
  y -= 2;
  drawLine(`Woli Agent Work - ${new Date().toISOString().slice(0, 10)}`, 8.5, regular, rgb(0.42, 0.46, 0.53), 2.2);

  for (const block of markdownBlocks(markdown)) {
    if (block.kind === "space") { y -= 5; continue; }
    if (block.kind === "heading") {
      const size = block.level === 1 ? 15 : block.level === 2 ? 13 : 11.5;
      y -= 7;
      for (const line of wrapPdfLine(block.text, bold, size, width)) drawLine(line, size, bold, dark, 1.35);
      y -= 2;
    } else if (block.kind === "bullet") {
      const lines = wrapPdfLine(block.text, regular, 10, width - 12);
      lines.forEach((line, i) => {
        if (i === 0) {
          if (y < margin + 14) addPage();
          draw("•", margin + 2, y - 10, 10, regular, ink);
        }
        drawLine(line, 10, regular, ink, 1.4, 12);
      });
      y -= 1;
    } else if (block.kind === "paragraph") {
      for (const line of wrapPdfLine(block.text, regular, 10, width)) drawLine(line, 10, regular, ink);
      y -= 2;
    } else {
      // A table: columns sized by their content, cells wrapped, the header repeated on a new page.
      const size = block.header.length > 8 ? 6.5 : block.header.length > 5 ? 7.5 : 8.5;
      const pad = 3;
      const lineH = size * 1.3;
      // Each column at least as wide as its longest word (no "2026-11-1 / 3"), the rest shared by content.
      const all = [block.header, ...block.rows];
      const longestWord = block.header.map((_, i) => Math.max(...all.map((r, n) => Math.max(...(r[i] ?? "").split(/\s+/).map((w) => textWidth(n === 0 ? bold : regular, w, size))))) + pad * 2 + 1);
      const natural = block.header.map((_, i) => Math.min(width * 0.4, Math.max(...all.map((r, n) => textWidth(n === 0 ? bold : regular, r[i] ?? "", size))) + pad * 2 + 1));
      const minSum = longestWord.reduce((a, b) => a + b, 0);
      let widths: number[];
      if (minSum >= width) widths = columnWidths(block, width);
      else {
        const want = natural.map((w, i) => Math.max(0, w - longestWord[i]));
        const wantSum = want.reduce((a, b) => a + b, 0) || 1;
        const spare = width - minSum;
        widths = longestWord.map((w, i) => w + (spare * want[i]) / wantSum);
      }
      const drawRow = (cells: string[], head: boolean) => {
        const face = head ? bold : regular;
        const wrapped = cells.map((c, i) => wrapPdfLine(c, face, size, widths[i] - pad * 2));
        const h = Math.max(...wrapped.map((w) => w.length)) * lineH + pad * 2;
        if (y - h < margin) {
          addPage();
          if (!head) drawRow(block.header, true);
        }
        if (head) page.drawRectangle({ x: margin, y: y - h, width, height: h, color: rgb(0.93, 0.95, 1) });
        let x = margin;
        wrapped.forEach((lines, i) => {
          lines.forEach((line, n) => draw(line, x + pad, y - pad - size - n * lineH + 1, size, face, head ? dark : ink));
          page.drawRectangle({ x, y: y - h, width: widths[i], height: h, borderColor: rule, borderWidth: 0.5 });
          x += widths[i];
        });
        y -= h;
      };
      y -= 3;
      drawRow(block.header, true);
      for (const row of block.rows) drawRow(row, false);
      y -= 6;
    }
  }
  return Buffer.from(await pdf.save());
}

export async function generateAgentArtifacts(args: { taskTitle: string; markdown: string; definitions: unknown }): Promise<GeneratedAgentArtifact[]> {
  const definitions = normalizeOutputDefinitions(args.definitions);
  const artifacts: GeneratedAgentArtifact[] = [];
  for (const definition of definitions) {
    const stem = artifactStem(args.taskTitle, definition.name);
    let artifact: GeneratedAgentArtifact;
    if (definition.format === "markdown") {
      artifact = { filename: `${stem}.md`, format: definition.format, type: "markdown", mimeType: "text/markdown; charset=utf-8", bytes: Buffer.from(args.markdown, "utf8"), contentText: args.markdown };
    } else if (definition.format === "text") {
      const text = blockLines(args.markdown).join("\n");
      artifact = { filename: `${stem}.txt`, format: definition.format, type: "text", mimeType: "text/plain; charset=utf-8", bytes: Buffer.from(text, "utf8"), contentText: text };
    } else if (definition.format === "json") {
      const text = JSON.stringify({ title: args.taskTitle, generatedAt: new Date().toISOString(), content: args.markdown }, null, 2);
      artifact = { filename: `${stem}.json`, format: definition.format, type: "json", mimeType: "application/json; charset=utf-8", bytes: Buffer.from(text, "utf8"), contentText: text };
    } else if (definition.format === "docx") {
      artifact = { filename: `${stem}.docx`, format: definition.format, type: "file", mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document", bytes: await makeDocx(args.taskTitle, args.markdown), contentText: null };
    } else if (definition.format === "xlsx") {
      artifact = { filename: `${stem}.xlsx`, format: definition.format, type: "file", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", bytes: makeXlsx(args.taskTitle, args.markdown), contentText: null };
    } else if (definition.format === "pptx") {
      artifact = { filename: `${stem}.pptx`, format: definition.format, type: "file", mimeType: "application/vnd.openxmlformats-officedocument.presentationml.presentation", bytes: await makePptx(args.taskTitle, args.markdown), contentText: null };
    } else {
      artifact = { filename: `${stem}.pdf`, format: definition.format, type: "file", mimeType: "application/pdf", bytes: await makePdf(args.taskTitle, args.markdown), contentText: null };
    }
    if (!artifact.bytes.length || artifact.bytes.length > MAX_ARTIFACT_BYTES) throw new Error(`Generated artifact is outside the allowed size: ${artifact.filename}`);
    artifacts.push(artifact);
  }
  return artifacts;
}
